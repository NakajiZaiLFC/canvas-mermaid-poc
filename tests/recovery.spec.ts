import { expect, test } from '@playwright/test'

test('reload of invalid code restores the last valid drawing without fixing or losing the source', async ({ page }) => {
  await page.goto('./')
  await expect(page.locator('.diagram svg')).toContainText('利用者')
  await page.locator('.diagram').click()
  await page.keyboard.press('Home'); await page.keyboard.insertText('broken ')
  await expect(page.locator('.diagram-error')).toBeVisible()
  await page.waitForTimeout(500)
  await page.reload()
  await expect(page.locator('.diagram-error')).toBeVisible()
  await expect(page.locator('.diagram svg')).toContainText('利用者')
  await page.locator('.diagram').click()
  await expect(page.locator('.mermaid-source')).toContainText(['```mermaid', 'broken flowchart LR'])
})

test('two tabs cannot silently overwrite each other; losing text stays editable and exportable', async ({ page, context }) => {
  await page.goto('./')
  await expect(page.getByRole('textbox', { name: 'ドキュメント' })).toBeVisible()
  const second = await context.newPage()
  await second.goto('./')
  await expect(second.getByRole('textbox', { name: 'ドキュメント' })).toBeVisible()
  await page.getByRole('textbox', { name: 'ドキュメント' }).focus()
  await page.keyboard.press('ControlOrMeta+a'); await page.keyboard.insertText('勝った保存')
  await page.waitForTimeout(500)
  await second.getByRole('textbox', { name: 'ドキュメント' }).focus()
  await second.keyboard.press('ControlOrMeta+a'); await second.keyboard.insertText('失いたくない別タブの入力')
  await expect(second.getByRole('status')).toContainText('別のタブ')
  await expect(second.getByRole('textbox', { name: 'ドキュメント' })).toContainText('失いたくない別タブの入力')
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'ドキュメント' })).toContainText('勝った保存')
  await second.keyboard.press('ControlOrMeta+Shift+P')
  const download = second.waitForEvent('download')
  await second.getByRole('button', { name: 'Markdownを書き出す' }).click()
  expect((await download).suggestedFilename()).toBe('canvas.md')
})
